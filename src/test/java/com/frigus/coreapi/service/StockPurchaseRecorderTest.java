import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/** Real JDBC and transaction proxies, without a full application or an external database. */
class StockPurchaseRecorderTest {
    private static final Instant NOW = Instant.parse("2026-10-31T10:30:00Z");
    private JdbcTemplate jdbc;
    private DataSourceTransactionManager transactions;
    private MoneySavingLedgerService ledger;
    private StockProductRepository lots;
    private StockRepository stocks;
    private ProductRepository products;
    private GroupAccessService access;
    private Stock stock;
    private Product product;
    private StockProduct createdLot;

    @BeforeEach
    void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        transactions = new DataSourceTransactionManager(source);
        jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE groups(id UUID PRIMARY KEY,deleted_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE stock_products(id INTEGER PRIMARY KEY,quantity INTEGER NOT NULL)");
        jdbc.execute("""
                CREATE TABLE food_purchases(id UUID PRIMARY KEY,group_id UUID NOT NULL REFERENCES groups(id),
                  purchase_date DATE NOT NULL,source VARCHAR(24) NOT NULL,idempotency_key VARCHAR(160) NOT NULL,
                  request_hash VARCHAR(64) NOT NULL,deleted_at TIMESTAMP,UNIQUE(group_id,idempotency_key))
                """);
        jdbc.execute("""
                CREATE TABLE food_purchase_lines(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  purchase_id UUID NOT NULL REFERENCES food_purchases(id),stock_key INTEGER NOT NULL,
                  stock_product_id INTEGER REFERENCES stock_products(id),product_id INTEGER,product_name VARCHAR NOT NULL,
                  category VARCHAR NOT NULL,category_group VARCHAR NOT NULL,unit_of_measure VARCHAR NOT NULL,
                  expire_date DATE NOT NULL,quantity INTEGER NOT NULL CHECK(quantity>0),unit_price NUMERIC(10,2) NOT NULL CHECK(unit_price>0))
                """);
        jdbc.execute("""
                CREATE TABLE money_supplies(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  stock_key INTEGER NOT NULL,stock_product_id INTEGER REFERENCES stock_products(id),
                  purchase_line_id BIGINT UNIQUE REFERENCES food_purchase_lines(id),available_on DATE NOT NULL,
                  quantity INTEGER NOT NULL CHECK(quantity>0),unknown_cost BOOLEAN NOT NULL)
                """);
        jdbc.execute("""
                CREATE TABLE money_exits(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  group_id UUID,stock_key INTEGER,stock_product_id INTEGER,product_name VARCHAR,category VARCHAR,
                  unit_of_measure VARCHAR,expire_date DATE,occurred_at TIMESTAMP,local_date DATE,quantity INTEGER,
                  kind VARCHAR,reason_code VARCHAR,movement_id INTEGER,discard_id INTEGER,canceled_at TIMESTAMP)
                """);
        jdbc.execute("""
                CREATE TABLE money_allocations(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  exit_id BIGINT REFERENCES money_exits(id),supply_id BIGINT REFERENCES money_supplies(id),
                  quantity INTEGER,amount NUMERIC(20,2),category_group VARCHAR)
                """);
        var group = Group.builder().id(UUID.randomUUID()).timeZone("Pacific/Kiritimati").build();
        jdbc.update("INSERT INTO groups(id) VALUES (?)", group.getId());
        stock = Stock.builder().id(3).group(group).build();
        product = Product.builder().id(7).name("Arroz").category(Category.GRAIN)
                .unitOfMeasure(UnitOfMeasure.UNIT).unitPrice(new BigDecimal("99.00")).build();
        lots = mock(StockProductRepository.class);
        stocks = mock(StockRepository.class);
        products = mock(ProductRepository.class);
        access = mock(GroupAccessService.class);
        ledger = new MoneySavingLedgerService(jdbc);
        when(stocks.findById(3)).thenReturn(Optional.of(stock));
        when(products.findById(7)).thenReturn(Optional.of(product));
        when(lots.saveAndFlush(any(StockProduct.class))).thenAnswer(invocation -> {
            createdLot = invocation.getArgument(0);
            createdLot.setId(11);
            // Emulates the flushed JPA insert on the very same transaction-bound connection.
            jdbc.update("INSERT INTO stock_products(id,quantity) VALUES (?,?)", 11, createdLot.getQuantity());
            return createdLot;
        });
    }

    @Test
    void creationRecordsActualPriceAndKnownSupplyWithoutDoublingTheLot() {
        var response = service(ledger).create(request(new BigDecimal("4.25"), 4));
        assertThat(response.getQuantity()).isEqualTo(4);
        assertThat(jdbc.queryForObject("SELECT quantity FROM stock_products WHERE id=11", Integer.class)).isEqualTo(4);
        assertThat(jdbc.queryForObject("SELECT source FROM food_purchases", String.class)).isEqualTo("USER_CONFIRMED");
        assertThat(jdbc.queryForObject("SELECT purchase_date FROM food_purchases", LocalDate.class)).isEqualTo(LocalDate.of(2026, 11, 1));
        assertThat(jdbc.queryForObject("SELECT unit_price FROM food_purchase_lines", BigDecimal.class)).isEqualByComparingTo("4.25");
        assertThat(jdbc.queryForObject("SELECT category_group FROM food_purchase_lines", String.class)).isEqualTo("GRAIN");
        assertThat(jdbc.queryForObject("SELECT stock_key FROM food_purchase_lines", Integer.class)).isEqualTo(11);
        ledger.ensureOpening(11, 4);
        assertThat(count("money_supplies")).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM money_supplies WHERE unknown_cost=true", Integer.class)).isZero();
    }

    @Test
    void recordingTheSameCreatedLotIsIdempotentEvenOnAnotherDay() {
        service(ledger).create(request(new BigDecimal("4.25"), 4));
        var tomorrow = proxied(new StockPurchaseRecorder(jdbc, ledger,
                Clock.fixed(NOW.plusSeconds(86400), ZoneOffset.UTC)));
        new TransactionTemplate(transactions).executeWithoutResult(status -> {
            tomorrow.lockGroup(stock.getGroup().getId());
            tomorrow.recordCreatedLot(createdLot);
        });
        assertThat(count("food_purchases")).isEqualTo(1);
        assertThat(count("food_purchase_lines")).isEqualTo(1);
        assertThat(count("money_supplies")).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT quantity FROM stock_products WHERE id=11", Integer.class)).isEqualTo(4);
    }

    @Test
    void subsequentConsumptionAllocatesTheConfirmedCostInsteadOfUnknownOpeningOrCatalogPrice() {
        service(ledger).create(request(new BigDecimal("4.25"), 4));
        new TransactionTemplate(transactions).executeWithoutResult(status -> {
            jdbc.update("UPDATE stock_products SET quantity=2 WHERE id=11");
            ledger.recordMovement(createdLot, 4, -2, "CONSUMED", null, NOW.plusSeconds(3600));
        });
        assertThat(jdbc.queryForObject("SELECT amount FROM money_allocations", BigDecimal.class)).isEqualByComparingTo("8.50");
        assertThat(jdbc.queryForObject("SELECT quantity FROM money_allocations", Integer.class)).isEqualTo(2);
        assertThat(count("money_supplies")).isEqualTo(1);
    }

    @Test
    void ledgerFailureRollsBackTheLotAndEveryPurchaseWriteTogether() {
        var failingLedger = mock(MoneySavingLedgerService.class);
        doThrow(new IllegalStateException("ledger failure")).when(failingLedger).rebuild(11);
        assertThatThrownBy(() -> service(failingLedger).create(request(new BigDecimal("4.25"), 4)))
                .isInstanceOf(IllegalStateException.class).hasMessage("ledger failure");
        assertThat(count("stock_products")).isZero();
        assertThat(count("food_purchases")).isZero();
        assertThat(count("food_purchase_lines")).isZero();
        assertThat(count("money_supplies")).isZero();
    }

    @Test
    void unpricedFoodRemainsUnpricedWithoutCreatingAPurchase() {
        service(ledger).create(request(null, 4));
        assertThat(count("stock_products")).isEqualTo(1);
        assertThat(count("food_purchases")).isZero();
        assertThat(count("money_supplies")).isZero();
    }

    @Test
    void pricedNonFoodRetainsItsSnapshotWithoutEnteringFoodMoneySaving() {
        product.setCategory(Category.CLEANING);
        var response = service(ledger).create(request(new BigDecimal("4.25"), 4));
        assertThat(response.getPurchaseUnitPrice()).isEqualByComparingTo("4.25");
        assertThat(count("food_purchases")).isZero();
        assertThat(count("money_supplies")).isZero();
    }

    @Test
    void emptyLotsDoNotInventFinancialUnits() {
        service(ledger).create(request(new BigDecimal("4.25"), 0));
        assertThat(count("stock_products")).isEqualTo(1);
        assertThat(count("food_purchases")).isZero();
        assertThat(count("money_supplies")).isZero();
    }

    @Test
    void recorderCannotBeCalledOutsideTheCreatingTransaction() {
        var recorder = proxied(new StockPurchaseRecorder(jdbc, ledger));
        assertThatThrownBy(() -> recorder.lockGroup(stock.getGroup().getId()))
                .isInstanceOf(IllegalTransactionStateException.class);
        assertThatThrownBy(() -> recorder.recordCreatedLot(new StockProduct()))
                .isInstanceOf(IllegalTransactionStateException.class);
    }

    private StockProductCreateRequestDto request(BigDecimal price, int quantity) {
        return StockProductCreateRequestDto.builder().stockId(3).productId(7).quantity(quantity)
                .purchaseUnitPrice(price).expireDate(LocalDate.of(2027, 1, 1)).build();
    }

    private StockProductService service(MoneySavingLedgerService ledgerService) {
        var recorder = proxied(new StockPurchaseRecorder(jdbc, ledgerService, Clock.fixed(NOW, ZoneOffset.UTC)));
        return proxied(new StockProductService(lots, new StockProductMapper(), stocks, products,
                access, new StockProductStatusResolver(), recorder));
    }

    @SuppressWarnings("unchecked")
    private <T> T proxied(T target) {
        var advice = new TransactionInterceptor(transactions, new AnnotationTransactionAttributeSource());
        var proxy = new ProxyFactory(target);
        proxy.setProxyTargetClass(true);
        proxy.addAdvice(advice);
        return (T) proxy.getProxy();
    }

    private int count(String table) { return jdbc.queryForObject("SELECT count(*) FROM " + table, Integer.class); }
}
